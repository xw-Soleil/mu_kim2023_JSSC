function print_mu_kim_results(results, section)
%PRINT_MU_KIM_RESULTS 输出简洁的数值结果。

if nargin < 2
    section = 'all';
end

if any(strcmp(section, {'all', 'methods', 'residue'}))
    fprintf('\n=== 四种更新方法：%dx%d 网格，MAE <= %.0e ===\n', ...
        results.config.convergence.grid_size, ...
        results.config.convergence.grid_size, ...
        results.config.convergence.mae_target);
    fprintf('%-15s %9s %12s %14s %15s\n', ...
        'Method', 'Updates', 'PE updates', 'Cycle proxy', 'Residue diff.');
    for method_id = 1:numel(results.method_names)
        fprintf('%-15s %9d %12d %14d %15.2e\n', ...
            results.method_names{method_id}, ...
            results.iterations(method_id), ...
            results.pe_updates(method_id), ...
            results.cycle_proxy(method_id), ...
            results.solution_difference(method_id));
    end
    fprintf('注：PE updates 和 Cycle proxy 是算法级代理量，不是芯片实测结果。\n');
end

if any(strcmp(section, {'all', 'quantization', 'dsm'}))
    q = results.quantization;
    fprintf('\n=== 量化 residue FDM：%dx%d 网格，%d 轮 ===\n', ...
        results.config.quantization.grid_size, ...
        results.config.quantization.grid_size, ...
        results.config.quantization.num_updates);
    fprintf('浮点参考 MAE：%.3e\n', q.final_float);
    fprintf('%-10s %14s %14s %13s\n', ...
        'Precision', 'Without DSM', 'With DSM', 'Improvement');
    for bit_id = 1:numel(q.bits)
        fprintf('%-10s %14.3e %14.3e %12.1fx\n', ...
            sprintf('%d-bit', q.bits(bit_id)), ...
            q.final_no_dsm(bit_id), q.final_dsm(bit_id), ...
            q.improvement(bit_id));
    end
end
end
